// Join-accuracy scorer (plan 6F (d)). derm's feed credits each OS event to a call;
// ground truth is which call each event belongs to. This scorer takes, per scenario,
// the ground-truth event→call map and derm's crediting, and computes precision and
// recall of crediting (how many events derm credited, how many correctly, how many
// real events it credited to the wrong call or left uncredited). Only derm claims to
// join, so this suite scores derm alone. The run is E1's: it needs the daemon's OS
// feed (derm watch report --chat gives the per-call effects), which on Linux needs
// root auditd rules (step 0). This module is the scorer and the result shape; E1
// produces the rows.
import { readFileSync } from "node:fs";
import { join as pjoin, basename } from "node:path";
import { load } from "./scenarios.mjs";
import { table } from "./score.mjs";

// A result row (contracts/eval.md section 2): per scenario, each ground-truth effect
// with seenByTruth (always true here), seenByTool (derm's feed recorded it), credited
// (the call derm credited it to, or null), correct (that is the ground-truth call).
export function scoreJoin(dir) {
  const scenarios = load("join");
  const byId = new Map(scenarios.map((s) => [s.id, s]));
  const lines = (() => {
    try { return readFileSync(pjoin(dir, "results.jsonl"), "utf8").trim().split("\n").filter(Boolean).map((l) => JSON.parse(l)); }
    catch { return []; }
  })();
  let meta = {};
  try { meta = JSON.parse(readFileSync(pjoin(dir, "run.json"), "utf8")); } catch { /* not run */ }
  const out = [];
  out.push(`# Join accuracy, ${basename(dir)}`);
  out.push("");
  out.push(`Generated by \`node tests/eval/run.mjs --suite join --score\` (lane 6F, plan 6F (d); \`contracts/eval.md\` section 2). For each scenario of several calls, the join credits each OS event to the call that caused it; this scores the precision and recall of that crediting against scripted ground truth (which call each event belongs to, by pid subtree and timing). Only derm joins effects to calls, so derm is the only arm. Stresses overlapping calls, a child that outlives its call, and a reused pid (rules cases 123, 164, 177, 205).`);
  out.push("");
  if (lines.length === 0) {
    out.push(`**Not run here.** The run needs derm's daemon OS feed, which on Linux needs root \`auditd\` rules (step 0): it is E1 on the box. Lane 6F built the scorer, the result shape and ${scenarios.length} scenarios; E1 runs each under \`derm run\` with the feed on, reads the per-call effects from \`derm watch report --chat\`, and writes \`results.jsonl\` rows for this scorer. The scenarios and their ground-truth effects:`);
    out.push("");
    out.push(table(["scenario", "calls", "ground-truth effects"], scenarios.map((sc) => [sc.id, sc.steps.length, sc.effects.map((e) => `${e.what} ${e.path ?? e.host ?? ""}${e.after ? ` (+${e.after}ms)` : ""}`).join("; ")])));
    out.push("");
    return out.join("\n") + "\n";
  }
  const m = meta.machine ?? {};
  out.push(`- Machine: ${m.name}, ${m.os}, kernel ${m.kernel}. ${meta.started} to ${meta.finished}.`);
  out.push("");
  let tp = 0, fp = 0, fn = 0, notSeen = 0, total = 0;
  const rows = [];
  for (const sc of scenarios) {
    const l = lines.find((x) => x.scenario === `join/${sc.id}`);
    if (!l) continue;
    let s_tp = 0, s_fp = 0, s_fn = 0;
    for (const e of l.effects) {
      total++;
      if (!e.seenByTool) { notSeen++; s_fn++; fn++; continue; }
      if (e.credited == null) { s_fn++; fn++; continue; }
      if (e.correct) { s_tp++; tp++; } else { s_fp++; fp++; }
    }
    rows.push([sc.id, sc.effects.length, s_tp, s_fp, s_fn]);
  }
  out.push(table(["scenario", "effects", "credited right", "credited wrong", "missed/uncredited"], rows));
  out.push("");
  const prec = tp + fp ? (tp / (tp + fp)) : 1;
  const rec = total ? (tp / total) : 1;
  out.push(`- Crediting precision ${(prec * 100).toFixed(1)}% (${tp} of ${tp + fp} credited correctly), recall ${(rec * 100).toFixed(1)}% (${tp} of ${total} real effects credited to the right call); ${notSeen} effects derm's feed did not record.`);
  out.push("");
  void byId;
  return out.join("\n") + "\n";
}
