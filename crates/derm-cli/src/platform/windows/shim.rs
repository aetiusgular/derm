//! Finding the program `derm run` starts on Windows, and reading npm's
//! `.cmd` shims so it never starts one through `cmd.exe` (note AU section 4;
//! proposed case AU-3).
//!
//! Why: `CreateProcessW` takes one command line and runs a batch file only
//! through `cmd.exe /c`, whose quoting cannot carry every argument; Rust's
//! `Command` escapes for cmd and refuses some arguments (std's "Batch file
//! special handling"). And Rust's PATH search appends `.exe` only
//! (`std/src/sys/process/windows.rs`, `resolve_exe`, 1.97.0), so an npm
//! install (`codex.cmd`) is not found at all. npm writes a `.cmd`, a `.ps1`
//! and a shell script per binary (`cmd-shim`); the `.cmd`'s last line runs
//! the package's program:
//!
//! ```text
//! cmd-shim 7.0.0 (npm 10.9.9) and 9.0.2, for a script with a shebang:
//!   IF EXIST "%dp0%\node.exe" ( SET "_prog=%dp0%\node.exe" ) ELSE ( SET "_prog=node" ... )
//!   endLocal & goto #_undefined_# 2>NUL || title %COMSPEC% & [set PATHEXT=... & ]"%_prog%" <args> "%dp0%\<target>" %*
//! for a target with no shebang (an executable):
//!   "%dp0%\<target>" <spaces> %*
//! ```
//!
//! (`cmd-shim` `lib/index.js` lines 61-120 at 9.0.2, read; both versions'
//! output is in `tests/windows/fixtures/cmd-shim/`, generated by running
//! each.) `derm run` reads that line and starts the program itself:
//! `node.exe <args> <script> <your arguments>`, as an argument list. A shim
//! it cannot read, or one that sets variables (`@SET NAME=value`, from an
//! `env -S` shebang), is refused, never run through `cmd.exe`.

use std::path::{Path, PathBuf};

/// What a `.cmd` shim runs.
#[derive(Clone, Debug, PartialEq, Eq)]
pub enum ShimTarget {
    /// A program run directly (`"%dp0%\<target>" %*`).
    Direct(PathBuf),
    /// An interpreter (from the script's shebang, `node` for npm's
    /// packages) and its arguments, then the script.
    Interpreted {
        /// `%dp0%\<prog>.exe`, which the shim prefers when it exists.
        local: PathBuf,
        /// The bare program name, looked up on PATH otherwise.
        prog: String,
        args: Vec<String>,
        script: PathBuf,
    },
}

/// A shim's text cut to its parts, before any file is looked at.
pub fn parse_cmd_shim(text: &str, dir: &Path) -> Result<ShimTarget, String> {
    let lines: Vec<&str> = text.lines().map(|l| l.trim_end_matches('\r')).collect();
    let head = [
        "@ECHO off",
        "GOTO start",
        ":find_dp0",
        "SET dp0=%~dp0",
        "EXIT /b",
        ":start",
        "SETLOCAL",
        "CALL :find_dp0",
    ];
    if lines.len() < head.len() + 1 || lines[..head.len()] != head {
        return Err("not an npm shim (its first lines differ)".into());
    }
    let body: Vec<&str> = lines[head.len()..]
        .iter()
        .copied()
        .filter(|l| !l.trim().is_empty())
        .collect();
    if body
        .iter()
        .any(|l| l.trim_start().to_ascii_uppercase().starts_with("@SET "))
    {
        return Err("the shim sets variables (an `env -S` shebang); derm does not reproduce cmd's expansion of them".into());
    }
    let last = body.last().ok_or("an npm shim with no command")?;
    let tail = last
        .strip_suffix(" %*")
        .ok_or("the shim's last line does not end in %*")?;
    if let Some(i) = tail.find("\"%_prog%\"") {
        // The interpreter form: the two SET "_prog=" lines name it.
        let sets: Vec<&str> = body
            .iter()
            .filter_map(|l| l.trim().strip_prefix("SET \"_prog="))
            .filter_map(|v| v.strip_suffix('"'))
            .collect();
        let [local, prog] = sets[..] else {
            return Err("the shim does not name its interpreter twice".into());
        };
        let local = local
            .strip_prefix("%dp0%\\")
            .ok_or("the shim's local interpreter is not beside it")?;
        if !local.to_ascii_lowercase().ends_with(".exe") || prog.contains(['%', '"', '\\', '/']) {
            return Err("the shim's interpreter is not a plain program name".into());
        }
        let rest = tail[i + "\"%_prog%\"".len()..].trim();
        let (args, script) = split_target(rest)?;
        return Ok(ShimTarget::Interpreted {
            local: join(dir, local)?,
            prog: prog.to_string(),
            args,
            script: join(dir, &script)?,
        });
    }
    // The direct form: the whole line is the target.
    let (args, target) = split_target(tail.trim())?;
    if !args.is_empty() {
        return Err("the shim passes arguments before a direct target".into());
    }
    Ok(ShimTarget::Direct(join(dir, &target)?))
}

/// `<args> "%dp0%\<target>"`: the shebang's arguments (plain words, as
/// cmd-shim copies them) and the target's path inside the shim's folder.
fn split_target(rest: &str) -> Result<(Vec<String>, String), String> {
    let open = rest
        .rfind("\"%dp0%\\")
        .ok_or("the shim's target is not beside it")?;
    let quoted = &rest[open + 1..];
    let close = quoted.find('"').ok_or("the shim's target is not quoted")?;
    if !quoted[close + 1..].trim().is_empty() {
        return Err("text after the shim's target".into());
    }
    let target = &quoted["%dp0%\\".len()..close];
    if target.contains(['%', '"']) {
        return Err("the shim's target holds a variable".into());
    }
    let args_text = rest[..open].trim();
    if args_text.contains(['%', '"', '&', '|', '<', '>', '^']) {
        return Err("the shim's arguments hold cmd syntax".into());
    }
    let args = args_text.split_whitespace().map(str::to_string).collect();
    Ok((args, target.to_string()))
}

/// The shim's folder joined with a relative target, `..` allowed (npm's
/// `.bin` points into `..\<package>`), an absolute or drive path refused.
fn join(dir: &Path, rel: &str) -> Result<PathBuf, String> {
    let rel_path = Path::new(rel);
    if rel.is_empty() || rel_path.is_absolute() || rel.contains(':') || rel.starts_with('\\') {
        return Err(format!(
            "the shim's target {rel:?} is not inside its folder's tree"
        ));
    }
    Ok(dir.join(rel_path))
}

/// The extensions tried, in order, for a bare program name (cmd's default
/// `PATHEXT` order for the four that start a program; `.exe` first is also
/// what `CreateProcessW` appends).
pub const EXTENSIONS: [&str; 4] = [".com", ".exe", ".bat", ".cmd"];

/// Finds `program` the way a shell on Windows would: as given when it holds
/// a folder, else in each PATH folder in turn, trying the name and then each
/// extension. `exists` is the file test (a real one, or a fake in tests).
pub fn find_program(
    program: &str,
    path_var: Option<&str>,
    exists: &dyn Fn(&Path) -> bool,
) -> Option<PathBuf> {
    let has_ext = Path::new(program).extension().is_some();
    let candidates = |base: PathBuf| -> Option<PathBuf> {
        if has_ext && exists(&base) {
            return Some(base);
        }
        EXTENSIONS.iter().find_map(|e| {
            let mut p = base.clone().into_os_string();
            p.push(e);
            let p = PathBuf::from(p);
            exists(&p).then_some(p)
        })
    };
    if program.contains(['\\', '/', ':']) {
        return candidates(PathBuf::from(program));
    }
    for dir in path_var
        .unwrap_or("")
        .split(';')
        .filter(|d| !d.trim().is_empty())
    {
        let dir = dir.trim().trim_matches('"');
        if let Some(p) = candidates(Path::new(dir).join(program)) {
            return Some(p);
        }
    }
    None
}

/// Whether a path names a batch file (`.bat` or `.cmd`, any case).
pub fn is_batch(p: &Path) -> bool {
    p.extension()
        .map(|e| {
            matches!(
                e.to_string_lossy().to_ascii_lowercase().as_str(),
                "bat" | "cmd"
            )
        })
        .unwrap_or(false)
}

/// What `derm run` starts for a program: a program and the arguments that
/// go before the caller's.
#[derive(Clone, Debug, PartialEq, Eq)]
pub struct Launch {
    pub program: PathBuf,
    pub leading: Vec<String>,
}

/// Turns a program name into what to start: a batch file is read as an npm
/// shim and replaced by its program; anything else starts as found.
pub fn launch_for(
    program: &str,
    path_var: Option<&str>,
    exists: &dyn Fn(&Path) -> bool,
    read: &dyn Fn(&Path) -> Option<String>,
) -> Result<Launch, String> {
    let found = find_program(program, path_var, exists).ok_or_else(|| {
        format!(
            "{program}: not found on PATH (tried {})",
            EXTENSIONS.join(", ")
        )
    })?;
    if !is_batch(&found) {
        return Ok(Launch {
            program: found,
            leading: Vec::new(),
        });
    }
    let refuse = |why: String| {
        format!(
            "refusing to start {} through cmd.exe: {why}. Start the program it names directly.",
            found.display()
        )
    };
    let text = read(&found).ok_or_else(|| refuse("it could not be read".into()))?;
    let dir = found.parent().unwrap_or(Path::new("."));
    match parse_cmd_shim(&text, dir).map_err(refuse)? {
        ShimTarget::Direct(target) => {
            if is_batch(&target) {
                return Err(refuse("it starts another batch file".into()));
            }
            Ok(Launch {
                program: target,
                leading: Vec::new(),
            })
        }
        ShimTarget::Interpreted {
            local,
            prog,
            args,
            script,
        } => {
            let interpreter = if exists(&local) {
                local
            } else {
                match find_program(&prog, path_var, exists) {
                    Some(p) if !is_batch(&p) => p,
                    Some(p) => {
                        return Err(refuse(format!(
                            "its interpreter {} is a batch file",
                            p.display()
                        )))
                    }
                    None => return Err(refuse(format!("its interpreter {prog} is not on PATH"))),
                }
            };
            let mut leading = args;
            leading.push(script.to_string_lossy().into_owned());
            Ok(Launch {
                program: interpreter,
                leading,
            })
        }
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    const ROOT: &str = env!("CARGO_MANIFEST_DIR");

    /// Whether two paths name the same file as Windows compares names: without
    /// regard to case or separator (tests use it for their fake file system).
    fn same(a: &Path, b: &Path) -> bool {
        let n = |p: &Path| p.to_string_lossy().replace('/', "\\").to_lowercase();
        n(a) == n(b)
    }

    fn fixture(version: &str, name: &str) -> String {
        let p = Path::new(ROOT)
            .join("../../tests/windows/fixtures/cmd-shim")
            .join(version)
            .join(format!("{name}.cmd"));
        std::fs::read_to_string(&p).unwrap_or_else(|e| panic!("{}: {e}", p.display()))
    }

    const BIN: &str = r"C:\proj\node_modules\.bin";

    #[test]
    fn both_cmd_shim_versions_read_to_node_and_the_script() {
        for v in ["v7.0.0", "v9.0.2"] {
            let t = parse_cmd_shim(&fixture(v, "codex"), Path::new(BIN)).unwrap();
            assert_eq!(
                t,
                ShimTarget::Interpreted {
                    local: Path::new(BIN).join("node.exe"),
                    prog: "node".into(),
                    args: vec![],
                    script: Path::new(BIN).join(r"..\@openai\codex\bin\codex.js"),
                },
                "{v}"
            );
            let t = parse_cmd_shim(&fixture(v, "flagged"), Path::new(BIN)).unwrap();
            let ShimTarget::Interpreted { args, script, .. } = t else {
                panic!("{v}")
            };
            assert_eq!(args, vec!["--no-warnings".to_string()], "{v}");
            assert!(script.ends_with(r"flagged\bin\f.js"), "{v}");
            let t = parse_cmd_shim(&fixture(v, "tool"), Path::new(BIN)).unwrap();
            assert_eq!(
                t,
                ShimTarget::Direct(Path::new(BIN).join(r"..\tool\bin\tool.exe")),
                "{v}"
            );
        }
    }

    #[test]
    fn a_shim_that_sets_variables_or_is_not_npms_is_refused() {
        for v in ["v7.0.0", "v9.0.2"] {
            let e = parse_cmd_shim(&fixture(v, "envy"), Path::new(BIN)).unwrap_err();
            assert!(e.contains("sets variables"), "{v}: {e}");
        }
        let codex = fixture("v9.0.2", "codex");
        for (what, text) in [
            ("hand-written", "@echo off\r\nnode x.js %*\r\n".to_string()),
            (
                "an extra command",
                codex
                    .replacen("\"%_prog%\"", "calc & \"%_prog%\"", 1)
                    .replace("calc & \"%_prog%\"", "\"%_prog%\" & calc"),
            ),
            (
                "a target outside",
                codex.replace(r#""%dp0%\..\@openai"#, r#""C:\evil\@openai"#),
            ),
            (
                "a variable in the target",
                codex.replace(r"\bin\codex.js", r"\%PAYLOAD%.js"),
            ),
            (
                "cmd syntax in the arguments",
                codex.replace("\"%_prog%\"  ", "\"%_prog%\" ^& "),
            ),
            ("no %* at the end", codex.replace(" %*", "")),
        ] {
            assert!(parse_cmd_shim(&text, Path::new(BIN)).is_err(), "{what}");
        }
    }

    fn fs(files: &'static [&'static str]) -> impl Fn(&Path) -> bool {
        move |p: &Path| files.iter().any(|f| same(p, Path::new(f)))
    }

    #[test]
    fn a_bare_name_is_found_with_its_extension_in_path_order() {
        let exists = fs(&[r"C:\a\codex.cmd", r"C:\b\codex.exe", r"C:\b\git.exe"]);
        let path = Some(r"C:\a;C:\b");
        assert_eq!(
            find_program("codex", path, &exists),
            Some(PathBuf::from(r"C:\a\codex.cmd"))
        );
        assert_eq!(
            find_program("git", path, &exists),
            Some(PathBuf::from(r"C:\b\git.exe"))
        );
        assert_eq!(
            find_program("codex.exe", path, &exists),
            Some(PathBuf::from(r"C:\b\codex.exe"))
        );
        assert_eq!(
            find_program(r"C:\b\git", None, &exists),
            Some(PathBuf::from(r"C:\b\git.exe"))
        );
        assert_eq!(find_program("nothing", path, &exists), None);
        assert_eq!(find_program("git", None, &exists), None);
    }

    #[test]
    fn an_npm_shim_launches_node_with_the_script_first() {
        let shim = fixture("v9.0.2", "codex");
        let exists = fs(&[r"C:\npm\codex.cmd", r"C:\node\node.exe"]);
        let read = move |p: &Path| same(p, Path::new(r"C:\npm\codex.cmd")).then(|| shim.clone());
        let l = launch_for("codex", Some(r"C:\npm;C:\node"), &exists, &read).unwrap();
        assert_eq!(l.program, PathBuf::from(r"C:\node\node.exe"));
        assert_eq!(
            l.leading,
            vec![r"C:\npm\..\@openai\codex\bin\codex.js".to_string()]
        );
        // node.exe beside the shim wins, as the shim's own IF EXIST does.
        let exists = fs(&[r"C:\npm\codex.cmd", r"C:\npm\node.exe", r"C:\node\node.exe"]);
        let shim = fixture("v7.0.0", "codex");
        let read = move |_: &Path| Some(shim.clone());
        let l = launch_for("codex", Some(r"C:\npm;C:\node"), &exists, &read).unwrap();
        assert_eq!(l.program, PathBuf::from(r"C:\npm\node.exe"));
    }

    #[test]
    fn a_batch_file_that_is_not_a_shim_is_refused_never_run_through_cmd() {
        let exists = fs(&[r"C:\x\setup.bat"]);
        let read = |_: &Path| Some("@echo off\r\npowershell -c evil\r\n".to_string());
        let e = launch_for("setup", Some(r"C:\x"), &exists, &read).unwrap_err();
        assert!(
            e.contains("refusing to start") && e.contains("cmd.exe"),
            "{e}"
        );
        let shim = fixture("v9.0.2", "codex");
        let read = move |_: &Path| Some(shim.clone());
        let exists = fs(&[r"C:\npm\codex.cmd"]);
        let e = launch_for("codex", Some(r"C:\npm"), &exists, &read).unwrap_err();
        assert!(e.contains("node is not on PATH"), "{e}");
        let e = launch_for("nope", Some(r"C:\npm"), &exists, &read).unwrap_err();
        assert!(e.contains("not found"), "{e}");
    }
}
